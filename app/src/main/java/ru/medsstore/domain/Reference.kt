    private fun norm(s: String): String =
        s.trim().lowercase().replace(Regex("[^a-zа-я0-9]"), "")

    private val index: Map<String, RefEntry> by lazy {
        val m = HashMap<String, RefEntry>(entries.size * 4)
        for (e in entries) {
            m[norm(e.inn)] = e
            for (a in e.aliases) m[norm(a)] = e
        }
        m
    }

    /** Точное совпадение по МНН или синониму. */
    fun find(inn: String): RefEntry? = index[norm(inn)]

    /** Подсказки по совпадению начала — для подсказок при вводе. */
    fun suggest(query: String, limit: Int = 6): List<RefEntry> {
        val q = norm(query)
        if (q.isEmpty()) return emptyList()
        return entries
            .filter { e ->
                val names = listOf(e.inn) + e.aliases
                names.any { norm(it).startsWith(q) || norm(it).contains(q) }
            }
            .take(limit)
    }
